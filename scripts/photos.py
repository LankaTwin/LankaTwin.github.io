"""Builds the landscape photos in public/photos/ from Wikimedia Commons originals.

    python3 scripts/photos.py <dir-with-downloads> scripts/photos.json

photos.json lists, for each scene, the Commons file, its author and licence (as shown on
the file page) and an optional crop: "box" [left, top, right, bottom] cuts out part of the
original first, "focusY" picks which band of a tall picture to keep. Each photo is cropped to 16:9, resized to 480, 960 and
1600 px wide and saved as WebP, and a tiny blurred preview is written into
src/lib/scenes.ts with the credits, so nothing about a photo is typed by hand twice.
"""
import base64
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

# Banner widths; quality falls as size grows (big banners sit under a dark gradient).
WIDTHS = {480: 70, 960: 62, 1600: 56}
ROOT = Path(__file__).resolve().parent.parent


def crop_16_9(im, focus_y=0.5):
    w, h = im.size
    target = w * 9 / 16
    if h > target:  # too tall: keep a band around focus_y
        top = int(min(max(0, focus_y * h - target / 2), h - target))
        return im.crop((0, top, w, top + int(target)))
    tw = int(h * 16 / 9)  # too wide: centre crop
    left = (w - tw) // 2
    return im.crop((left, 0, left + tw, h))


def main(src_dir, manifest):
    picks = json.loads(Path(manifest).read_text())
    out_dir = ROOT / 'public' / 'photos'
    out_dir.mkdir(parents=True, exist_ok=True)
    entries = []
    for scene, p in picks.items():
        im = ImageOps.exif_transpose(Image.open(Path(src_dir) / p['file'])).convert('RGB')
        if 'box' in p:
            im = im.crop(tuple(p['box']))
        im = crop_16_9(im, p.get('focusY', 0.5))
        sizes = {}
        for w in WIDTHS:
            if w > im.width * 1.05:  # a hair of upscaling is fine, more is blur
                continue
            r = im.resize((w, round(w * 9 / 16)), Image.LANCZOS)
            path = out_dir / f'{scene}-{w}.webp'
            r.save(path, 'WEBP', quality=WIDTHS[w], method=6)
            sizes[w] = path.stat().st_size
        # A 32×18 px blurred preview, inlined as a data URI for an instant placeholder.
        tiny = im.resize((32, 18), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1))
        buf = io.BytesIO()
        tiny.save(buf, 'WEBP', quality=40)
        lqip = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
        entries.append((scene, p, sorted(sizes), lqip))
        print(scene, {w: f'{s // 1024} KB' for w, s in sizes.items()}, f'preview {len(lqip)} B')

    lines = [
        '// Generated by scripts/photos.py from scripts/photos.json. Real photos of the island\'s',
        '// landscapes from Wikimedia Commons, credited to their authors under their licences.',
        "import type { Zone } from './places'",
        '',
        'export interface ScenePhoto {',
        '  /** Widths available as /photos/<scene>-<w>.webp. */',
        '  widths: number[]',
        '  /** Tiny blurred preview shown while the photo loads. */',
        '  lqip: string',
        '  /** English description for alt text and credits. */',
        '  title: string',
        '  author: string',
        '  license: string',
        '  licenseUrl: string',
        '  /** The file page on Wikimedia Commons. */',
        '  page: string',
        '}',
        '',
        "export const SCENES: Record<Zone | 'flood', ScenePhoto> = {",
    ]
    for scene, p, widths, lqip in entries:
        lines += [
            f'  {scene}: {{',
            f'    widths: {json.dumps(widths)},',
            f"    lqip: '{lqip}',",
            f'    title: {json.dumps(p["title"], ensure_ascii=False)},',
            f'    author: {json.dumps(p["author"], ensure_ascii=False)},',
            f'    license: {json.dumps(p["license"])},',
            f'    licenseUrl: {json.dumps(p["licenseUrl"])},',
            f'    page: {json.dumps(p["page"])},',
            '  },',
        ]
    lines += [
        '}',
        '',
        "export const sceneSrc = (scene: keyof typeof SCENES, w: number) => `/photos/${scene}-${w}.webp`",
        'export const sceneSrcSet = (scene: keyof typeof SCENES) => SCENES[scene].widths.map((w) => `${sceneSrc(scene, w)} ${w}w`).join(\', \')',
        '',
    ]
    (ROOT / 'src' / 'lib' / 'scenes.ts').write_text('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
