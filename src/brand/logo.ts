/** Longitude/latitude bounds of the outline: west, south, east, north. */
export const ISLAND_BBOX = [79.6958, 5.9241, 81.8918, 9.8298] as const

export const BRAND = {
  lagoon: '#0E6E78',
  lagoonHi: '#14919A',
  deep: '#0A4F57',
  gold: '#E9A81C',
  canvas: '#F4F7F6',
  mint: '#7FD3CF',
  ink: '#12262E',
}

const f = (n: number) => n.toFixed(2)

export interface MarkOptions {
  /** Shrink the artwork about the centre (0.78 keeps a maskable icon's safe zone). */
  safe?: number
  /** Corner radius of the tile, in 64ths; 0 for full-bleed icons. */
  rx?: number
  /** Use the detailed coastline (large sizes). */
  detail?: boolean
  /** Unique id prefix when several marks share a document. */
  id?: string
  /** Extra attributes for the root <svg>, e.g. 'class="x" aria-hidden="true"'. */
  attrs?: string
}

/** The mark as an SVG string in a 64×64 viewBox. */
export function markSvg({ safe = 1, rx = 14, detail = false, id = 'lt', attrs = '' }: MarkOptions = {}) {
  const path = detail ? ISLAND_DETAIL : ISLAND_ICON
  const z = (v: number) => 32 + (v - 32) * safe
  const sc = (49 * safe) / 100
  const tx = z(29.5) - (ISLAND_W * sc) / 2
  const ty = z(33.5) - 50 * sc
  const [w, s, , n] = ISLAND_BBOX
  const k = Math.cos((7.8 * Math.PI) / 180)
  const u = 100 / (n - s)
  // Pulse over the hill country (80.82°E, 7.45°N).
  const px = tx + (80.82 - w) * k * u * sc
  const py = ty + (n - 7.45) * u * sc
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" ${attrs}>` +
    `<defs><linearGradient id="${id}-g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${BRAND.lagoonHi}"/><stop offset="1" stop-color="${BRAND.deep}"/></linearGradient></defs>` +
    `<rect width="64" height="64" rx="${rx}" fill="url(#${id}-g)"/>` +
    `<circle cx="${f(z(47.5))}" cy="${f(z(16))}" r="${f(5.4 * safe)}" fill="${BRAND.gold}"/>` +
    `<path d="${path}" transform="translate(${f(tx + 2.6 * safe)} ${f(ty + 2.2 * safe)}) scale(${sc.toFixed(4)})" fill="none" stroke="${BRAND.mint}" stroke-width="${f((1.5 * safe) / sc)}" stroke-linejoin="round" opacity=".9"/>` +
    `<path d="${path}" transform="translate(${f(tx)} ${f(ty)}) scale(${sc.toFixed(4)})" fill="${BRAND.canvas}"/>` +
    `<circle cx="${f(px)}" cy="${f(py)}" r="${f(2.6 * safe)}" fill="${BRAND.lagoon}"/>` +
    `<circle cx="${f(px)}" cy="${f(py)}" r="${f(5.2 * safe)}" fill="none" stroke="${BRAND.lagoon}" stroke-width="${f(1.3 * safe)}" opacity=".45"/>` +
    '</svg>'
}
